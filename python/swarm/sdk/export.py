"""``python -m swarm.sdk export``: turn a validated perception brain into what the device toolchain takes.

* ``.swm`` brain   -> the compiled network plus the exact ``setup_device.py prepare --model ... --library ...``
  command (the C++ engine runs it; on MCUs link ``swarm_core`` and load the same file).
* python brain     -> a ``--brain-dir`` folder: the package as an importable module plus ``_device.py``, a
  runtime factory that feeds the brain uint8 CHW frames and answers like the native handler.
* mesh policy      -> the arena network compiled to ``.swm`` plus its input layout and output decoding.
* tactic           -> refused: tactics model coordination in the simulator; the runtime has its own scheduler.

Nothing is signed, copied to USB or run on a device here - that stays an explicit operator step
(docs/DEPLOYMENT.md).
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

from .packages import Package, PackageError, load_package
from .validate import scan_imports

DEVICE_ADAPTER = '''"""Device-runtime factory for the __NAME__ perception brain (generated by `python -m swarm.sdk export`).

swarm.runtime calls make_handler(options) once and then handler(payload) per observation. The payload is
the frame as uint8 CHW bytes already resized to the brain input; the answer mirrors the native handler:
8 bytes (network order uint32 class, float32 confidence) when the class is not empty and confident
enough, otherwise an empty "nothing useful" result.
"""

import struct

import numpy as np

from swarm.runtime.node import InferenceResult

from .__MODULE__ import __CLASS__


def make_handler(options):
    options = dict(options or {})
    threshold = float(options.get("threshold", 0.5))
    empty_class = int(options.get("empty_class", 0))
    brain = __CLASS__(**_kwargs(__CLASS__, options))
    shape = tuple(int(d) for d in brain.input_shape)
    count = shape[0] * shape[1] * shape[2]

    def handler(payload):
        if not isinstance(payload, (bytes, bytearray)) or len(payload) != count:
            raise ValueError(f"expected {count} bytes of uint8 CHW input")
        image = np.frombuffer(bytes(payload), dtype=np.uint8).reshape(shape).astype(np.float32) / 255.0
        pred, conf = brain.classify(image)
        pred, conf = int(pred), float(conf)
        useful = pred != empty_class and conf >= threshold
        return InferenceResult(struct.pack("!If", pred, conf) if useful else b"", useful)

    return handler


def _kwargs(cls, options):
    import inspect

    params = inspect.signature(cls).parameters
    out = {}
    if "seed" in params:
        out["seed"] = int(options.get("seed", 0))
    if "options" in params:
        out["options"] = dict(options.get("brain_options", __OPTIONS__))
    return out
'''


def _fresh_dir(out: Path) -> Path:
    out = Path(out)
    if out.exists() and any(out.iterdir()):
        raise PackageError(f"{out} exists and is not empty - choose a new export folder")
    out.mkdir(parents=True, exist_ok=True)
    return out


def export_for_device(path: str | Path, out: str | Path, target: str = "linux-aarch64") -> dict:
    """Writes the device artefacts to ``out`` (new or empty); returns ``{"out", "kind", "factory", "instructions"}``."""
    pkg = load_package(path)
    if pkg.type == "tactic":
        raise PackageError(f"{pkg.name} is a tactic: tactics run in the simulator only. The device runtime "
                           "(swarm.runtime) has its own bounded load balancer; port a winning policy there deliberately.")
    if pkg.type == "policy":
        return _export_policy(pkg, out)
    if pkg.format == "swm":
        return _export_swm(pkg, out, target)
    return _export_python(pkg, out, target)


def _export_policy(pkg: Package, out: str | Path) -> dict:
    if pkg.format != "npz":
        raise PackageError(f"{pkg.name} is a Python arena policy: it runs in the simulator (and could on a Linux "
                           "companion with your own glue). Train a mesh network for the same role to get a .swm "
                           "that the C++ engine runs on every drone, MCUs included.")
    from swarm.arena.brains import DECODE_NOTES, FEATURE_NAMES, OUTPUT_NAMES, ROWS

    brain = pkg.make_policy()
    out = _fresh_dir(out)
    dest = brain.to_swm(out / f"{pkg.name}.swm")
    rows = ROWS[brain.role]
    inputs = "\n".join(f"  {i:>2}  {n}" for i, n in enumerate(FEATURE_NAMES[brain.role]))
    text = f"""{pkg.label()} - arena {brain.role} brain compiled for the C++ engine
network: {brain.n_in} inputs -> Dense {brain.hidden} -> ReLU -> Dense {brain.n_out} outputs (f32)
cost: {brain.macs} MACs per drone per decision ({rows} network run{'s' if rows > 1 else ''})

Load {dest.name} into swarm::Model (cpp/, any target) or the Python runtime's native handler and feed it,
every decision, the float32 input vector{' of each option row' if rows > 1 else ''} below - built from the
drone's own sensors and what it heard on the mesh radio, normalised exactly as named (docs/ARENA.md):
{inputs}

outputs: {', '.join(OUTPUT_NAMES[brain.role])}
decode:  {DECODE_NOTES[brain.role]}

The glue that builds these inputs from real sensors and turns the decoded action into autopilot set
points is integration work per airframe; keep it bit-compatible with swarm/arena (clash.py / recon.py),
which is the reference implementation the network was trained on.
"""
    (out / "DEPLOY.txt").write_text(text, encoding="utf-8")
    return {"out": str(out), "kind": "policy", "factory": "swarm::Model", "instructions": text}


def _export_swm(pkg: Package, out: str | Path, target: str) -> dict:
    model = pkg.model_path
    if model is None or not model.is_file():
        raise PackageError(f"{pkg.name}: model {pkg.manifest.get('model')!r} not built yet - run its train.py")
    from .packages import swm_info

    info = swm_info(model)
    out = _fresh_dir(out)
    dest = out / f"{pkg.name}.swm"
    shutil.copyfile(model, dest)
    cap = max(1 << 20, int(info["weights_bytes"] * 4))
    text = f"""{pkg.label()} - compiled network ({info['macs']} MACs/frame, {'int8' if info['int8'] else 'f32'},
input {'x'.join(map(str, info['input_shape']))}, {info['n_classes']} classes)

Linux companion (Raspberry Pi class), through the encrypted runtime:
  1. build the engine ON the target (or with a Linux cross toolchain):
       cmake -S . -B build-pi -G Ninja -DCMAKE_BUILD_TYPE=Release -DSWARM_NATIVE_ARCH=OFF -DSWARM_BUILD_TESTS=OFF
       cmake --build build-pi            -> build-pi/bin/swarm_brain.so
  2. prepare the inference-only payload on the operator PC:
       python setup_device.py prepare --config <node.json> --model {dest.as_posix()} --library <path/to/swarm_brain.so> --output <NEW folder> --target {target} --ram-cap-bytes {cap}
  3. sign, encrypt, copy to USB and install explicitly: docs/DEPLOYMENT.md

Microcontroller (Cortex-M4/M7, CubeSat OBC), bare metal:
  build cpp/ (swarm_core) with your board's toolchain and load {dest.name} into swarm::Model
  under the board's RAM cap; `python -m swarm.sdk validate` printed the RAM each profile needs.
"""
    (out / "DEPLOY.txt").write_text(text, encoding="utf-8")
    return {"out": str(out), "kind": "swm", "factory": "swarm.runtime.handlers:make_native_handler",
            "instructions": text}


def _export_python(pkg: Package, out: str | Path, target: str) -> dict:
    imports, broken = scan_imports(pkg.root)
    if broken:
        raise PackageError(f"{pkg.name}: does not parse: {broken[0]}")
    if "swarm" in imports:
        raise PackageError(f"{pkg.name} imports swarm.* - the device payload carries only the runtime; "
                           "remove the import (subclassing PerceptionBrain is optional) to deploy it")
    file_part, cls_name = pkg.entry.split(":")
    module = f"{pkg.name}_brain"
    out = _fresh_dir(out)
    dest = out / module
    shutil.copytree(pkg.root, dest, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".git", "*.zip"))
    if not (dest / "__init__.py").exists():
        (dest / "__init__.py").write_text(f'"""{pkg.title} (exported by swarm.sdk)."""\n', encoding="utf-8")
    options = pkg.manifest.get("options") or {}
    adapter = (DEVICE_ADAPTER.replace("__NAME__", pkg.name).replace("__MODULE__", file_part[:-3].replace("/", "."))
               .replace("__CLASS__", cls_name).replace("__OPTIONS__", repr(dict(options))))
    (dest / "_device.py").write_text(adapter, encoding="utf-8")
    factory = f"{module}._device:make_handler"
    brain_block = {"factory": factory, "options": {"threshold": 0.5, "empty_class": 0}}
    third_party = sorted(imports - {"numpy"} - set(sys.stdlib_module_names))
    text = f"""{pkg.label()} - Python perception brain for Linux companions (not for MCU-class members)

The device needs Python 3.10+ and numpy{', ' + ', '.join(third_party) if third_party else ''} installed by the operator.
  1. put this block in the node configuration (node.json) as "brain":
{json.dumps(brain_block, indent=2)}
  2. prepare the payload on the operator PC:
       python setup_device.py prepare --config <node.json> --brain-dir {out.as_posix()} --output <NEW folder> --target {target}
  3. sign, encrypt, copy to USB and install explicitly: docs/DEPLOYMENT.md
Input on the device is uint8 CHW already resized to the brain input; class 0 is "nothing".
"""
    (out / "DEPLOY.txt").write_text(text, encoding="utf-8")
    return {"out": str(out), "kind": "python", "factory": factory, "instructions": text}
